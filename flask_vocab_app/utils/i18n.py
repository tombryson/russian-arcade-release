def normalize_ui_language(value):
    if value in SUPPORTED_UI_LANGUAGES:
        return value
    return "en"


def translate_ui(key, language="en"):
    language = normalize_ui_language(language)
    value = UI_TRANSLATIONS.get(key)
    if not value:
        return key
    return value.get(language) or value.get("en") or key
