def russian_speech(text):
    """A conservative output check, not an input-language or grammar detector.

    The café worker needs no Latin words. Learner transcripts are never passed
    through this check: mixed speech, names and wrong endings remain evidence.
    """
    letters = [c for c in text if c.isalpha()]
    return bool(letters) and all(re.fullmatch('[А-Яа-яЁё]', c) for c in letters)


